#!/usr/bin/env python3
"""Give every public page its own description, canonical and social titles.

The site grew a brand partial that gives each page the same Open Graph block — the library's title
and description — and the per-page heading tags that a 339-page site needs were applied once, by
hand, and then lost the next time the generators ran. That is also why CI's `git diff --exit-code`
step kept failing: the committed HTML and the generated HTML disagreed.

This runs at the end of `build:assets` and writes those tags from each page's own content, so the
generated output is both correct and stable. Deterministic on purpose: same input, same bytes, and
running it twice changes nothing.

    python3 scripts/fix-page-meta.py
"""
from __future__ import annotations

import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUB = ROOT / "apps" / "web" / "public"
BASE = "https://open-practice.open-practice.workers.dev"
MARKER = "<!-- social + icons: generated by scripts/apply-brand.py, safe to leave alone -->"
MAX_DESC = 155

TITLE_RE = re.compile(r"<title>(.*?)</title>", re.S | re.I)
H1_RE = re.compile(r"<h1[^>]*>(.*?)</h1>", re.S | re.I)
P_RE = re.compile(r"<p(?:\s[^>]*)?>(.*?)</p>", re.S | re.I)
TAG_RE = re.compile(r"<[^>]+>")


def text(fragment: str) -> str:
    s = TAG_RE.sub(" ", fragment)
    s = html.unescape(s)
    return re.sub(r"\s+", " ", s).strip()


def meta(html_text: str, prop: str, attr: str = "property") -> str | None:
    m = re.search(rf'<meta {attr}="{re.escape(prop)}" content="([^"]*)"', html_text)
    return m.group(1) if m else None


def shorten(s: str, limit: int = MAX_DESC) -> str:
    s = s.strip()
    if len(s) <= limit:
        return s
    cut = s[:limit]
    stop = max(cut.rfind(". "), cut.rfind(" — "), cut.rfind(", "), cut.rfind(" "))
    if stop > limit * 0.6:
        cut = cut[:stop]
    return cut.rstrip(" ,.;:—-") + "…"


def page_url(rel: Path) -> str:
    posix = rel.as_posix()
    if posix == "index.html":
        return BASE + "/"
    if posix.endswith("/index.html"):
        return f"{BASE}/{posix[: -len('index.html')]}"
    return f"{BASE}/{posix}"


def set_meta(s: str, prop: str, content: str) -> str:
    esc = html.escape(content, quote=True)
    pattern = re.compile(rf'<meta property="{re.escape(prop)}" content="[^"]*">')
    if pattern.search(s):
        return pattern.sub(f'<meta property="{prop}" content="{esc}">', s, count=1)
    return s.replace("</head>", f'<meta property="{prop}" content="{esc}"></head>', 1)


def set_twitter(s: str, prop: str, content: str) -> str:
    esc = html.escape(content, quote=True)
    pattern = re.compile(rf'<meta name="twitter:{re.escape(prop)}" content="[^"]*">')
    if pattern.search(s):
        return pattern.sub(f'<meta name="twitter:{prop}" content="{esc}">', s, count=1)
    return s.replace("</head>", f'<meta name="twitter:{prop}" content="{esc}"></head>', 1)


def fix_one(path: Path) -> bool:
    rel = path.relative_to(PUB)
    s = path.read_text()
    if "</head>" not in s:
        return False
    original = s

    title_m = TITLE_RE.search(s)
    raw_title = text(title_m.group(1)) if title_m else "Open Practice"
    title = re.sub(r"\s*·\s*Open Practice$", "", raw_title) or "Open Practice"
    if title.endswith("Open Practice") and len(title) > len("Open Practice"):
        title = title[: -len("Open Practice")].rstrip(" ·—-")

    # description: what the page already says, best source first, never the library's copy
    desc = meta(s, "description", "name") or ""
    if not desc:
        for candidate in (H1_RE.search(s), P_RE.search(s)):
            if candidate:
                candidate_text = text(candidate.group(1))
                if len(candidate_text) > 40:
                    desc = candidate_text
                    break
    if not desc:
        desc = meta(s, "og:description") or "Free, practical AI education from Open Practice."
    desc = shorten(desc)

    url = page_url(rel)

    # description and canonical go just before the brand block, which is where they were written
    head_meta = f'<meta name="description" content="{html.escape(desc, quote=True)}">' \
                f'<link rel="canonical" href="{url}">'
    s = re.sub(r'<meta name="description" content="[^"]*">', "", s)
    s = re.sub(r'<link rel="canonical" href="[^"]*">', "", s)
    if MARKER in s:
        s = s.replace(MARKER, head_meta + MARKER, 1)
    else:
        s = s.replace("</head>", head_meta + "</head>", 1)

    for prop, value in (("og:title", title), ("og:description", desc), ("og:url", url)):
        s = set_meta(s, prop, value)
    for prop, value in (("twitter:title", title), ("twitter:description", desc)):
        s = set_twitter(s, prop, value)

    if s != original:
        path.write_text(s)
        return True
    return False


def main() -> int:
    pages = sorted(p for p in PUB.rglob("*.html") if p.is_file())
    changed = [p for p in pages if fix_one(p)]
    for p in changed:
        print(f"  meta: {p.relative_to(PUB)}")
    print(f"  {len(pages)} pages · {len(changed)} updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
